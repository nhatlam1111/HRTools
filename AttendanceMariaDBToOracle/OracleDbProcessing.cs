            string procedureSql = System.IO.File.ReadAllText(procedureFilePath);
            try
            {
                using (var connection = new OracleConnection(connectionString))
                {
                    connection.Open();
                    using (var command = new OracleCommand(procedureSql.Replace("\r\n", " "), connection))
                    {
                        command.CommandType = CommandType.Text;
                        command.ExecuteNonQuery();
                    }
                }
                LogController.Information("Successfully created HR_PRO_TRANSFER_FROM_ALPETA procedure.");
                Console.WriteLine("Successfully created HR_PRO_TRANSFER_FROM_ALPETA procedure."); // For console output
                return true;
            }
            catch (Exception ex)
            {
                LogController.Error($"Error creating procedure: {ex.Message}");
                Console.WriteLine($"Error creating procedure: {ex.Message}"); // For console output
                return false;
            }
        }

