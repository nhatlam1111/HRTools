        }

        public bool CheckProcedureExist()
        {
            string sql = $"SELECT COUNT(*) FROM USER_PROCEDURES WHERE OBJECT_NAME = 'HR_PRO_TRANSFER_FROM_ALPETA'";
            using (var connection = new OracleConnection(connectionString))
            {
                connection.Open();
                using (var command = new OracleCommand(sql, connection))
                {
                    var result = command.ExecuteScalar();
                    return Convert.ToInt32(result) > 0;
                }
            }
        }

        private bool CheckTableExists()
        {
            string sql = @"
                SELECT COUNT(*) FROM USER_TABLES 
                WHERE TABLE_NAME = 'THR_TERMINAL_LOGS'
            ";

            try
            {
                using (var connection = new OracleConnection(connectionString))
                {
                    connection.Open();
                    using (var command = new OracleCommand(sql, connection))
                    {
                        var result = command.ExecuteScalar();
                        return Convert.ToInt32(result) > 0;
                    }
                }
            }
            catch (Exception ex)
            {
                LogController.Error($"Error checking table existence: {ex.Message}");
                Console.WriteLine($"Error checking table existence: {ex.Message}"); // For console output
                return false;
            }
        }

        private bool CreateTable()
        {
            string createTableSql = @"
                CREATE TABLE THR_TERMINAL_LOGS (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    TERMINAL_ID NUMBER(10) NOT NULL,
                    USER_ID NUMBER(10) NOT NULL,
                    USER_NAME VARCHAR2(100),
                    CARD_ID VARCHAR2(50),
                    EVENT_TIME DATE NOT NULL,
                    AUTH_TYPE NUMBER(5) DEFAULT 0,
                    AUTH_RESULT NUMBER(5) DEFAULT 0,
                    CREATED_DATE DATE DEFAULT SYSDATE
                )
            ";

            string createIndexSql = @"
                CREATE INDEX IDX_THR_TERMINAL_LOGS_TIME ON THR_TERMINAL_LOGS (EVENT_TIME)
            ";

            try
            {
                using (var connection = new OracleConnection(connectionString))
                {
                    connection.Open();
                    using (var transaction = connection.BeginTransaction())
                    {
                        try
                        {
                            // Create table
                            using (var command = new OracleCommand(createTableSql, connection))
                            {
                                command.Transaction = transaction;
                                command.ExecuteNonQuery();
                            }

                            // Create index
                            using (var command = new OracleCommand(createIndexSql, connection))
                            {
                                command.Transaction = transaction;
                                command.ExecuteNonQuery();
                            }

                            transaction.Commit();
                            LogController.Information("Successfully created THR_TERMINAL_LOGS table and index.");
                            Console.WriteLine("Successfully created THR_TERMINAL_LOGS table and index."); // For console output
                            return true;
                        }
                        catch (Exception ex)
                        {
                            transaction.Rollback();
                            LogController.Error($"Error creating table, transaction rolled back: {ex.Message}");
                            Console.WriteLine($"Error creating table, transaction rolled back: {ex.Message}"); // For console output
                            return false;
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                LogController.Error($"Error connecting to Oracle DB for table creation: {ex.Message}");
                Console.WriteLine($"Error connecting to Oracle DB for table creation: {ex.Message}"); // For console output
                return false;
            }
        }

        public bool CreateProcedure()
