    internal class OracleDbProcessing
    {
        // This class will handle the processing of data to Oracle DB
        // It will include methods to connect to the database, insert data,
        // and process it as needed for the application.
        DatabaseInfo db;
        string configPath = AppDomain.CurrentDomain.BaseDirectory + "oracle.config";
        string connectionString = string.Empty;
        OracleConnection? connection;

        public ConnectionState ConnectionState
        {
            get
            {
                if (connection == null)
                    return ConnectionState.Closed;
                return connection.State;
            }
        }

