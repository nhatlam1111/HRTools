        public bool InsertTerminalLogs(List<TerminalLog> logs)
        {
            if (logs == null || logs.Count == 0)
            {
                Console.WriteLine("No terminal logs to insert.");
                LogController.Information("No terminal logs to insert.");
                return true;
            }

            // Filter out existing logs first to improve performance
            var newLogs = FilterNewLogs(logs);
            
            if (newLogs.Count == 0)
            {
                Console.WriteLine("All logs already exist in Oracle DB. No insertion needed.");
                LogController.Information("All logs already exist in Oracle DB. No insertion needed.");
                return true;
            }

            string sql = @"
                INSERT INTO THR_TERMINAL_LOGS 
                (TERMINAL_ID, USER_ID, USER_NAME, CARD_ID, EVENT_TIME, AUTH_TYPE, AUTH_RESULT)
                VALUES 
                (:TerminalId, :UserId, :UserName, :CardId, :EventTime, :AuthType, :AuthResult)
            ";

            try
            {
                using (var connection = new OracleConnection(connectionString))
                {
                    connection.Open();
                    using (var transaction = connection.BeginTransaction())
                    {
                        try
                        {
                            using (var command = new OracleCommand(sql, connection))
                            {
                                command.Transaction = transaction;
                                
                                // Add parameters
                                command.Parameters.Add(":TerminalId", OracleDbType.Int32);
                                command.Parameters.Add(":UserId", OracleDbType.Int32);
                                command.Parameters.Add(":UserName", OracleDbType.Varchar2, 100);
                                command.Parameters.Add(":CardId", OracleDbType.Varchar2, 50);
                                command.Parameters.Add(":EventTime", OracleDbType.Date);
                                command.Parameters.Add(":AuthType", OracleDbType.Int32);
                                command.Parameters.Add(":AuthResult", OracleDbType.Int32);

                                int idx = 0;
                                foreach (var log in newLogs)
                                {
                                    command.Parameters[":TerminalId"].Value = log.TerminalId;
                                    command.Parameters[":UserId"].Value = log.UserId;
                                    command.Parameters[":UserName"].Value = log.UserName ?? "";
                                    command.Parameters[":CardId"].Value = log.CardId ?? "";
                                    command.Parameters[":EventTime"].Value = log.EventTime;
                                    command.Parameters[":AuthType"].Value = log.AuthType;
                                    command.Parameters[":AuthResult"].Value = log.AuthResult;

                                    command.ExecuteNonQuery();

                                    LogController.Information($"Inserted log: TerminalId={log.TerminalId}, UserId={log.UserId}, EventTime={log.EventTime}");

                                    Console.SetCursorPosition(0, Console.CursorTop); // Reset cursor position for console output
                                    Console.Write($"Inserted log: {++idx}/{newLogs.Count}"); // For console output
                                }
                            }

                            using (var command = new OracleCommand())
                            { 
                                command.Connection = connection;
                                command.Transaction = transaction;
                                command.CommandType = CommandType.StoredProcedure;
                                command.CommandText = "HR_PRO_TRANSFER_FROM_ALPETA"; // Call the procedure to transfer data
                                command.ExecuteNonQuery();
                                LogController.Information("Called HR_PRO_TRANSFER_FROM_ALPETA procedure to transfer data.");
                                Console.WriteLine("Called HR_PRO_TRANSFER_FROM_ALPETA procedure to transfer data."); // For console output
                            }

                            transaction.Commit();
                            Console.WriteLine($"Successfully inserted {newLogs.Count} new terminal logs to Oracle DB (filtered from {logs.Count} total logs).");
                            LogController.Information($"Successfully inserted {newLogs.Count} new terminal logs to Oracle DB (filtered from {logs.Count} total logs).");
                            return true;
                        }
                        catch (Exception ex)
                        {
                            transaction.Rollback();
                            Console.WriteLine($"Error inserting terminal logs, transaction rolled back: {ex.Message}");
                            LogController.Error($"Error inserting terminal logs, transaction rolled back: {ex.Message}");
                            throw;
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Error connecting to Oracle DB: {ex.Message}");
                LogController.Error($"Error connecting to Oracle DB: {ex.Message}");
                return false;
            }
        }

        public HashSet<string> GetExistingLogKeys(DateTime fromDate, DateTime toDate)
        {
            string sql = @"
                SELECT TERMINAL_ID || '|' || USER_ID || '|' || TO_CHAR(EVENT_TIME, 'YYYY-MM-DD HH24:MI:SS') as LogKey
                FROM THR_TERMINAL_LOGS
                WHERE EVENT_TIME >= :FromDate AND EVENT_TIME <= :ToDate
            ";

            HashSet<string> existingKeys = new HashSet<string>();

            try
            {
                using (var connection = new OracleConnection(connectionString))
                {
                    connection.Open();
                    using (var command = new OracleCommand(sql, connection))
                    {
                        command.Parameters.Add(":FromDate", OracleDbType.Date).Value = fromDate;
                        command.Parameters.Add(":ToDate", OracleDbType.Date).Value = toDate;

                        using (var reader = command.ExecuteReader())
                        {
                            while (reader.Read())
                            {
                                var logKey = reader["LogKey"]?.ToString();
                                if (!string.IsNullOrEmpty(logKey))
                                    existingKeys.Add(logKey);
                            }
                        }
                    }
                }

                LogController.Information($"Retrieved {existingKeys.Count} existing log keys from Oracle DB for optimization.");
                Console.WriteLine($"Retrieved {existingKeys.Count} existing log keys from Oracle DB for optimization."); // For console output
                return existingKeys;
            }
            catch (Exception ex)
            {
                LogController.Error($"Error retrieving existing log keys: {ex.Message}");
                Console.WriteLine($"Error retrieving existing log keys: {ex.Message}"); // For console output
                return new HashSet<string>();
            }
        }

        public List<TerminalLog> FilterNewLogs(List<TerminalLog> logs)
        {
            if (logs == null || logs.Count == 0)
                return new List<TerminalLog>();

            // Get date range from logs
            var minDate = logs.Min(l => l.EventTime).Date;
            var maxDate = logs.Max(l => l.EventTime).Date.AddDays(1);

            // Get existing log keys
            var existingKeys = GetExistingLogKeys(minDate, maxDate);

            // Filter out existing logs
            var newLogs = logs.Where(log =>
            {
                string logKey = $"{log.TerminalId}|{log.UserId}|{log.EventTime:yyyy-MM-dd HH:mm:ss}";
                return !existingKeys.Contains(logKey);
            }).ToList();

            LogController.Information($"Filtered {logs.Count - newLogs.Count} existing logs. {newLogs.Count} new logs to insert.");
            Console.WriteLine($"Filtered {logs.Count - newLogs.Count} existing logs. {newLogs.Count} new logs to insert."); // For console output
            return newLogs;
        }
    }
